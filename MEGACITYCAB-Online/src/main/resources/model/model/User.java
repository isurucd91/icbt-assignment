package model;

public class User {
	public int getmRegNo() {
		return mRegNo;
	}
	public void setmRegNo(int mRegNo) {
		this.mRegNo = mRegNo;
	}
	public String getmName() {
		return mName;
	}
	public void setmName(String mName) {
		this.mName = mName;
	}
	public String getmAddress() {
		return mAddress;
	}
	public void setmAddress(String mAddress) {
		this.mAddress = mAddress;
	}
	public String getmNIC() {
		return mNIC;
	}
	public void setmNIC(String mNIC) {
		this.mNIC = mNIC;
	}
	public String getmEmail() {
		return mEmail;
	}
	public void setmEmail(String mEmail) {
		this.mEmail = mEmail;
	}
	public String getmPassword() {
		return mPassword;
	}
	public void setmPassword(String mPassword) {
		this.mPassword = mPassword;
	}
	public String getmType() {
		return mType;
	}
	public void setmType(String mType) {
		this.mType = mType;
	}
	public String getmTelePhoneNo() {
		return mTelePhoneNo;
	}
	public void setmTelePhoneNo(String mTelePhoneNo) {
		this.mTelePhoneNo = mTelePhoneNo;
	}
	private int mRegNo;
	private String mName;
	private String mAddress;
	private String mNIC;
	private String mEmail;
	private String mPassword;
	private String mType;
	private String mTelePhoneNo;


}
